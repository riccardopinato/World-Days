def _source(url):
    return {"tier": "A_PRIMARY", "url": url, "verifiedAt": VERIFIED}

def _authority(name, typ="GOVERNMENT", resolution=None):
    return {
        "name": name,
        "type": typ,
        "officiality": "OFFICIAL_INSTITUTIONAL",
        "resolution": resolution,
    }

